<?php

namespace SeekaHost\Forwarding;

/**
 * Builds the self-contained files deployed to a forwarded domain's document root.
 * The runtime script is plain PHP 5.6+ so it works on any hosting server.
 */
class Generator
{
    const DEFAULT_PARKING = '<!DOCTYPE html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">'
        . '<title>{domain}</title></head><body style="font-family:sans-serif;text-align:center;padding:80px 20px;color:#333">'
        . '<h1>{domain}</h1><p>This domain is parked.</p></body></html>';

    /**
     * @param array $rules rows from the URL forwarders table (already filtered by policy)
     * @return array filename => content
     */
    public static function build($domain, array $rules, $parkingHtml = '')
    {
        $compiled = [];
        foreach ($rules as $r) {
            $compiled[] = [
                'p' => rtrim($r->source_path, '/'),
                'd' => $r->destination,
                't' => (string) $r->type,
                'h' => isset($r->www_mode) ? (string) $r->www_mode : 'both',
                'w' => (bool) $r->wildcard,
                'q' => (bool) $r->preserve_query,
                'title' => (string) $r->title,
                'desc' => (string) $r->meta_description,
                'kw' => (string) $r->meta_keywords,
            ];
        }
        // Most specific path first; the root rule ("") always comes last.
        usort($compiled, function ($a, $b) {
            return strlen($b['p']) - strlen($a['p']);
        });

        $flags = defined('JSON_INVALID_UTF8_SUBSTITUTE') ? JSON_INVALID_UTF8_SUBSTITUTE : 0;
        $json = json_encode($compiled, $flags);
        if ($json === false) {
            throw new \RuntimeException('Could not encode forwarding rules: ' . json_last_error_msg());
        }
        $parking = str_replace('{domain}', htmlspecialchars(Validator::toUnicode($domain), ENT_QUOTES, 'UTF-8'),
            trim((string) $parkingHtml) !== '' ? $parkingHtml : self::DEFAULT_PARKING);

        return [
            '.htaccess' => self::htaccess(),
            'index.php' => self::script($domain, $json, $parking, empty($compiled)),
        ];
    }

    private static function htaccess()
    {
        return "# Generated by SeekaHost Domain & Email Forwarding. Changes will be overwritten.\n"
            . "DirectoryIndex index.php\n"
            . "Options -Indexes\n"
            . "<IfModule mod_rewrite.c>\n"
            . "RewriteEngine On\n"
            . "RewriteCond %{REQUEST_URI} !^/\\.well-known/\n"
            . "RewriteCond %{REQUEST_URI} !^/index\\.php$\n"
            . "RewriteRule ^ index.php [L]\n"
            . "</IfModule>\n"
            . "ErrorDocument 404 /index.php\n";
    }

    private static function script($domain, $json, $parkingHtml, $parkedOnly)
    {
        $payload = base64_encode($json);
        $parking = base64_encode($parkingHtml);
        $parkedOnly = $parkedOnly ? 'true' : 'false';
        $generated = date('Y-m-d H:i:s');
        $safeDomain = preg_replace('/[^a-z0-9.\-]/i', '', $domain);

        return <<<PHP
<?php
/*
 * Generated by SeekaHost Domain & Email Forwarding for {$safeDomain} on {$generated}.
 * Do not edit: this file is overwritten whenever forwarding rules change.
 */
\$rules = json_decode(base64_decode('{$payload}'), true);
\$parkedOnly = {$parkedOnly};
\$uri = isset(\$_SERVER['REQUEST_URI']) ? \$_SERVER['REQUEST_URI'] : '/';
\$path = explode('?', \$uri, 2);
\$path = explode('#', \$path[0], 2);
\$path = \$path[0];
if (\$path === '' || \$path[0] !== '/') {
    \$path = '/' . ltrim(\$path, '/');
}
if (\$path === '/index.php') {
    \$path = '/';
}
\$qs = isset(\$_SERVER['QUERY_STRING']) ? \$_SERVER['QUERY_STRING'] : '';
if (\$qs === '' && isset(\$_SERVER['REDIRECT_QUERY_STRING'])) {
    \$qs = \$_SERVER['REDIRECT_QUERY_STRING'];
}
\$host = strtolower(isset(\$_SERVER['HTTP_HOST']) ? preg_replace('/:\\d+\$/', '', \$_SERVER['HTTP_HOST']) : '');
\$isWww = strpos(\$host, 'www.') === 0;
\$trimmed = rtrim(\$path, '/');

foreach ((array) \$rules as \$r) {
    if ((\$r['h'] === 'www' && !\$isWww) || (\$r['h'] === 'nowww' && \$isWww)) {
        continue;
    }
    \$rest = null;
    if (\$r['p'] === '') {
        \$rest = \$r['w'] ? ltrim(\$path, '/') : '';
    } elseif (strcasecmp(\$trimmed, \$r['p']) === 0) {
        \$rest = '';
    } elseif (\$r['w'] && stripos(\$path, \$r['p'] . '/') === 0) {
        \$rest = substr(\$path, strlen(\$r['p']) + 1);
    }
    if (\$rest === null) {
        continue;
    }

    \$fragment = '';
    \$dest = \$r['d'];
    if ((\$hashPos = strpos(\$dest, '#')) !== false) {
        \$fragment = substr(\$dest, \$hashPos);
        \$dest = substr(\$dest, 0, \$hashPos);
    }
    \$parts = explode('?', \$dest, 2);
    \$target = \$parts[0];
    if (\$rest !== '') {
        \$target = rtrim(\$target, '/') . '/' . \$rest;
    }
    \$query = isset(\$parts[1]) ? \$parts[1] : '';
    if (\$r['q'] && \$qs !== '') {
        \$query = \$query === '' ? \$qs : \$query . '&' . \$qs;
    }
    if (\$query !== '') {
        \$target .= '?' . \$query;
    }
    \$target = str_replace(array("\\r", "\\n"), '', \$target . \$fragment);

    header('Cache-Control: no-cache, no-store, must-revalidate');
    if (\$r['t'] === 'masked') {
        \$h = function (\$v) { return htmlspecialchars(\$v, ENT_QUOTES, 'UTF-8'); };
        header('Content-Type: text/html; charset=UTF-8');
        echo '<!DOCTYPE html><html><head><meta charset="utf-8">'
            . '<meta name="viewport" content="width=device-width, initial-scale=1">'
            . '<title>' . \$h(\$r['title']) . '</title>'
            . (\$r['desc'] !== '' ? '<meta name="description" content="' . \$h(\$r['desc']) . '">' : '')
            . (\$r['kw'] !== '' ? '<meta name="keywords" content="' . \$h(\$r['kw']) . '">' : '')
            . '<style>html,body{margin:0;padding:0;height:100%;overflow:hidden}iframe{border:0;width:100%;height:100%;display:block}</style>'
            . '</head><body><iframe src="' . \$h(\$target) . '" title="' . \$h(\$r['title']) . '" allowfullscreen></iframe></body></html>';
        exit;
    }

    \$codes = array('301' => 301, '302' => 302, '303' => 303);
    header('Location: ' . \$target, true, isset(\$codes[\$r['t']]) ? \$codes[\$r['t']] : 301);
    exit;
}

header('Cache-Control: no-cache, no-store, must-revalidate');
header('Content-Type: text/html; charset=UTF-8');
if (\$parkedOnly) {
    echo base64_decode('{$parking}');
    exit;
}
http_response_code(404);
echo '<!DOCTYPE html><html><head><meta charset="utf-8"><title>Not Found</title></head>'
    . '<body style="font-family:sans-serif;text-align:center;padding:60px"><h1>Not Found</h1>'
    . '<p>No forwarding is configured for this address.</p></body></html>';

PHP;
    }
}
