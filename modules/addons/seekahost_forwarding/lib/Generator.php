<?php

namespace SeekaHost\Forwarding;

/**
 * Builds the self-contained files deployed to a forwarded domain's document root.
 * The runtime script is plain PHP 5.6+ so it works on any hosting server.
 */
class Generator
{
    /**
     * @param array $rules rows from the URL forwarders table
     * @return array filename => content
     */
    public static function build($domain, array $rules)
    {
        $compiled = [];
        foreach ($rules as $r) {
            $compiled[] = [
                'p' => rtrim($r->source_path, '/'),
                'd' => $r->destination,
                't' => $r->type,
                'w' => (bool) $r->wildcard,
                'q' => (bool) $r->preserve_query,
                'title' => (string) $r->title,
                'desc' => (string) $r->meta_description,
                'kw' => (string) $r->meta_keywords,
            ];
        }
        // Most specific path first; the root rule ("") always comes last.
        usort($compiled, function ($a, $b) {
            return strlen($b['p']) - strlen($a['p']);
        });

        return [
            '.htaccess' => self::htaccess(),
            'index.php' => self::script($domain, $compiled),
        ];
    }

    private static function htaccess()
    {
        return "# Generated by SeekaHost Domain & Email Forwarding. Changes will be overwritten.\n"
            . "DirectoryIndex index.php\n"
            . "Options -Indexes\n"
            . "<IfModule mod_rewrite.c>\n"
            . "RewriteEngine On\n"
            . "RewriteCond %{REQUEST_URI} !^/\\.well-known/\n"
            . "RewriteCond %{REQUEST_URI} !^/index\\.php$\n"
            . "RewriteRule ^ index.php [L]\n"
            . "</IfModule>\n"
            . "ErrorDocument 404 /index.php\n";
    }

    private static function script($domain, array $rules)
    {
        $payload = base64_encode(json_encode($rules));
        $generated = date('Y-m-d H:i:s');

        return <<<PHP
<?php
/*
 * Generated by SeekaHost Domain & Email Forwarding for {$domain} on {$generated}.
 * Do not edit: this file is overwritten whenever forwarding rules change.
 */
\$rules = json_decode(base64_decode('{$payload}'), true);
\$uri = isset(\$_SERVER['REQUEST_URI']) ? \$_SERVER['REQUEST_URI'] : '/';
\$path = parse_url(\$uri, PHP_URL_PATH);
if (!is_string(\$path) || \$path === '') {
    \$path = '/';
}
if (\$path === '/index.php') {
    \$path = '/';
}
\$qs = isset(\$_SERVER['QUERY_STRING']) ? \$_SERVER['QUERY_STRING'] : '';
\$trimmed = rtrim(\$path, '/');

foreach ((array) \$rules as \$r) {
    \$rest = null;
    if (\$r['p'] === '') {
        \$rest = \$r['w'] ? ltrim(\$path, '/') : '';
    } elseif (strcasecmp(\$trimmed, \$r['p']) === 0) {
        \$rest = '';
    } elseif (\$r['w'] && stripos(\$path, \$r['p'] . '/') === 0) {
        \$rest = substr(\$path, strlen(\$r['p']) + 1);
    }
    if (\$rest === null) {
        continue;
    }

    \$parts = explode('?', \$r['d'], 2);
    \$target = \$parts[0];
    if (\$rest !== '') {
        \$target = rtrim(\$target, '/') . '/' . \$rest;
    }
    \$query = isset(\$parts[1]) ? \$parts[1] : '';
    if (\$r['q'] && \$qs !== '') {
        \$query = \$query === '' ? \$qs : \$query . '&' . \$qs;
    }
    if (\$query !== '') {
        \$target .= '?' . \$query;
    }
    \$target = str_replace(array("\\r", "\\n"), '', \$target);

    if (\$r['t'] === 'masked') {
        \$h = function (\$v) { return htmlspecialchars(\$v, ENT_QUOTES, 'UTF-8'); };
        header('Content-Type: text/html; charset=UTF-8');
        echo '<!DOCTYPE html><html><head><meta charset="utf-8">'
            . '<meta name="viewport" content="width=device-width, initial-scale=1">'
            . '<title>' . \$h(\$r['title']) . '</title>'
            . (\$r['desc'] !== '' ? '<meta name="description" content="' . \$h(\$r['desc']) . '">' : '')
            . (\$r['kw'] !== '' ? '<meta name="keywords" content="' . \$h(\$r['kw']) . '">' : '')
            . '<style>html,body{margin:0;padding:0;height:100%;overflow:hidden}iframe{border:0;width:100%;height:100%;display:block}</style>'
            . '</head><body><iframe src="' . \$h(\$target) . '" title="' . \$h(\$r['title']) . '" allowfullscreen></iframe></body></html>';
        exit;
    }

    header('Cache-Control: no-cache');
    header('Location: ' . \$target, true, \$r['t'] === '302' ? 302 : 301);
    exit;
}

http_response_code(404);
header('Content-Type: text/html; charset=UTF-8');
echo '<!DOCTYPE html><html><head><meta charset="utf-8"><title>Not Found</title></head>'
    . '<body style="font-family:sans-serif;text-align:center;padding:60px"><h1>Not Found</h1>'
    . '<p>No forwarding is configured for this address.</p></body></html>';

PHP;
    }
}
